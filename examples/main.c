static bool wait_for_ip(uint32_t timeout_ms)
{
    const absolute_time_t deadline = make_timeout_time_ms(timeout_ms);
    while (!sta_has_ip())
    {
        if (time_reached(deadline))
            return false;
        cyw43_arch_poll();
        sleep_ms(20);
    }
    return true;
}

